import assert from 'node:assert/strict';
import { openPage } from './cdp.mjs';
const page = await openPage(Number(process.argv[2] ?? 9444));
try {
  await page.call('Page.enable');
  await page.call('Page.navigate', { url: `${process.env.EDENA_ORIGIN ?? 'http://127.0.0.1:5173'}/legacy.html` });
  await new Promise(resolve => setTimeout(resolve, 300));
  const result = await page.evaluate(`(async () => {
    const { WebGPUView, Visual, Text, lineSegments, LabelLayer, plotFrame, PlotLayer } = await import('/build/index.js');
    document.body.innerHTML = '<div id="stage" style="position:relative;width:400px;height:240px"><canvas style="width:400px;height:240px"></canvas></div>';
    const host = document.querySelector('#stage'), canvas = host.querySelector('canvas');
    const view = await WebGPUView.create(canvas, { interactive: false, antialias: false, maxDpr: 1 });
    const errors = []; view.device.addEventListener('uncapturederror', e => errors.push(e.error.message));
    view.camera.yaw = 0; view.camera.pitch = 0; view.camera.height = 2;
    const line = new Visual(lineSegments([[-1, 0, 0], [1, 0, 0]]), [1,1,1,1]);
    view.world.add(line);
    const read = async () => {
      view.render(true); await view.device.queue.onSubmittedWorkDone();
      const image = new Image(); image.src = canvas.toDataURL(); await image.decode();
      const copy = document.createElement('canvas'); copy.width = canvas.width; copy.height = canvas.height;
      const context = copy.getContext('2d'); context.drawImage(image, 0, 0);
      return context.getImageData(0, 0, copy.width, copy.height).data;
    };
    const coverage = data => { let sum=0,partial=0;for(let y=0;y<240;y++){const a=data[(y*400+200)*4+3];sum+=a/255;if(a>0&&a<255)partial++;}return {sum,partial}; };
    const close = coverage(await read());
    view.camera.height = 5;
    const far = coverage(await read());
    let replacementBuffers = 0;
    const createBuffer = view.device.createBuffer.bind(view.device);
    view.device.createBuffer = (...args) => { replacementBuffers++; return createBuffer(...args); };
    line.geometry = lineSegments([[-1,.1,0],[1,.1,0]]);
    await read();
    view.device.createBuffer = createBuffer;
    view.world.clear(); view.camera.height=2;
    const labels = new LabelLayer(host, view.camera);
    const italic = labels.add('ffff', () => [0,0,0], '#ffffff', 'left');
    italic.style.font = 'italic 40px serif';
    const settle = async () => { for(let i=0;i<16;i++){labels.update();view.render();await new Promise(r=>requestAnimationFrame(r));} };
    await settle();
    const text = await read();
    const rect=italic.getBoundingClientRect(), stage=host.getBoundingClientRect();
    let overhang=0;
    for(let y=0;y<240;y++)for(let x=Math.ceil(rect.right-stage.left);x<400;x++)if(text[(y*400+x)*4+3]>20)overhang++;
    labels.remove(italic);
    const edge = labels.add('A complete label', () => [1.5, .8, 0], '#ffffff', 'left', { billboard: true });
    edge.style.font = '20px serif'; await settle();
    const edgeRect=edge.getBoundingClientRect();
    const contained = edgeRect.right <= stage.right - 3 && edgeRect.bottom <= stage.bottom;
    labels.remove(edge);
    const plot = new PlotLayer(view.world, labels, plotFrame([-1,1],[-1,1],{xTicks:2,yTicks:2}));
    await settle();
    const tick = plot.tickLabels.find(label => label.textContent === '1' && label.style.marginTop === '5px');
    const tickRect = tick.getBoundingClientRect(), projected = view.camera.project([1,-.05,0],400,240);
    const tickError = [Math.abs((tickRect.left+tickRect.right)/2-stage.left-projected[0]), Math.abs(tickRect.top-stage.top-projected[1]-5)];
    const initialLabels = host.querySelectorAll('span').length;
    const originalLabels = [...plot.tickLabels];
    let plotUploads=0;
    const upload=view.device.queue.copyExternalImageToTexture.bind(view.device.queue);
    view.device.queue.copyExternalImageToTexture=(...args)=>{plotUploads++;return upload(...args);};
    for(let i=0;i<20;i++)plot.update(plotFrame([-1,1],[-1,1],{xTicks:2,yTicks:2}));
    await settle();
    const sameLabels=originalLabels.every((label,index)=>label===plot.tickLabels[index]);
    const retainedLabels = host.querySelectorAll('span').length, parts = plot.group.children.filter(node => !(node instanceof Text)).length;
    view.device.queue.copyExternalImageToTexture=upload;
    const shifted=plotFrame([-1,1],[-1,1],{xTicks:2,yTicks:2});
    for(const anchor of shifted.labels)anchor.position[0]+=.25;
    plot.update(shifted);await settle();
    const movedTick=plot.tickLabels.find(label=>label.textContent==='1'&&label.style.marginTop==='5px');
    const movedTickError=Math.abs(movedTick.getBoundingClientRect().left-tickRect.left-30);
    plot.update(plotFrame([-1,1],[-1,1],{xTicks:4,yTicks:4}));await settle();
    plot.update(plotFrame([-1,1],[-1,1],{xTicks:2,yTicks:2}));await settle();
    const shrunkLabels=host.querySelectorAll('span').length;
    plot.dispose(); labels.dispose(); view.dispose();
    // The whole-canvas option creates the same supported 4× MSAA path used by the demos.
    const aa = await WebGPUView.create(canvas,{interactive:false,antialias:true,maxDpr:1});
    aa.device.addEventListener('uncapturederror', e => errors.push(e.error.message));
    aa.world.add(line); aa.render(); await aa.device.queue.onSubmittedWorkDone(); aa.dispose();
    return {close,far,replacementBuffers,overhang,contained,tickError,initialLabels,retainedLabels,sameLabels,plotUploads,movedTickError,shrunkLabels,parts,errors};
  })()`);
  console.log(JSON.stringify(result, null, 2));
  assert.deepEqual(result.errors, []);
  assert.ok(Math.abs(result.close.sum - 1.8) < .1, 'default strokes cover 1.8 CSS pixels');
  assert.ok(result.close.partial > 0, 'stroke edges are antialiased even without MSAA');
  assert.ok(Math.abs(result.close.sum - result.far.sum) < .01, 'zoom preserves stroke thickness');
  assert.equal(result.replacementBuffers, 0, 'replacing equal-size strokes reuses their GPU buffers');
  assert.ok(result.overhang > 0, 'italic ink beyond the advance box survives rasterization');
  assert.ok(result.contained, 'labels near the canvas edge remain inside it');
  assert.ok(result.tickError.every(error => error < 1), 'tick labels align with projected tick endpoints');
  assert.equal(result.initialLabels, result.retainedLabels, 'rebuilding a plot releases old labels');
  assert.ok(result.movedTickError < 1, 'reused labels follow updated tick positions');
  assert.equal(result.shrunkLabels, result.initialLabels, 'shrinking an axis removes surplus labels');
  assert.ok(result.sameLabels, 'unchanged plot labels retain their DOM and scene objects');
  assert.equal(result.plotUploads, 0, 'unchanged plot labels retain their glyph textures');
  assert.equal(result.parts, 5, 'rebuilding a plot reuses its five frame objects');
} finally { await page.close(); }
